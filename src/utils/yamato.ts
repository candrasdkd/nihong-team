const WEIGHT_SIZE_BANDS = [
  { size: 60, maxWeightKg: 2 },
  { size: 80, maxWeightKg: 5 },
  { size: 100, maxWeightKg: 10 },
  { size: 120, maxWeightKg: 15 },
  { size: 140, maxWeightKg: 20 },
  { size: 160, maxWeightKg: 25 },
  { size: 180, maxWeightKg: 30 },
] as const;

export interface YamatoEstimate {
  size: number;
  maxWeightKg: number;
  amountYen: number;
  originRegion: YamatoRegion;
  destinationRegion: YamatoRegion;
  usesSamePrefectureRate: boolean;
}

export function estimateYamatoByRouteAndWeight(
  origin: YamatoPrefecture,
  destination: YamatoPrefecture,
  weightKg: number,
): YamatoEstimate | null {
  if (!Number.isFinite(weightKg) || weightKg <= 0 || weightKg > 30) return null;

  const band = WEIGHT_SIZE_BANDS.find(({ maxWeightKg }) => weightKg <= maxWeightKg);
  if (!band) return null;

  const originRegion = YAMATO_PREFECTURE_ZONES[origin];
  const destinationRegion = YAMATO_PREFECTURE_ZONES[destination];
  const rateRow = CASH_RATES_BY_ORIGIN[originRegion][
    String(band.size) as "60" | "80" | "100" | "120" | "140" | "160" | "180" | "200"
  ];
  const destinationIndex = YAMATO_REGIONS.indexOf(destinationRegion);
  const usesSamePrefectureRate = origin === destination;
  const amountYen = usesSamePrefectureRate
    ? (rateRow[0] ?? rateRow[destinationIndex + 1])
    : rateRow[destinationIndex + 1];

  if (amountYen == null) return null;

  return {
    size: band.size,
    maxWeightKg: band.maxWeightKg,
    amountYen,
    originRegion,
    destinationRegion,
    usesSamePrefectureRate,
  };
}
